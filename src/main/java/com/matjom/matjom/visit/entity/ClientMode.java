package com.matjom.matjom.visit.entity;
/*
 * [비즈니스 요약 — ClientMode]
 * - 위치 샘플(VisitPosition)·세션(Visit)의 “수집/사용 맥락”을 간단히 구분하는 플래그.
 * - 현재 코드 기준 값은 2개
 *   NAVIGATION: 적극적 사용(길 안내/포그라운드 등) — 짧은 간격 전송, 정확도 높음 기대.
 *   IDLE      : 소극적/대기(백그라운드/저전력 등) — 전송 간격 길고 정확도 보수적.
 * - 활용
 *   1) 품질/성공률 리포트(모드별 자동 도착 비율, 평균 dwell 시간).
 *   2) 지오펜스 정책 차등(예: IDLE에선 정확도 임계↑, 최소 간격↑).
 * - 주의
 *   - 과거 문서/코멘트에서 언급한 AUTO/MANUAL은 현재 enum에는 존재하지 않음
 *   - “수동 도착(버튼)” 여부는 ClientMode가 아니라 이벤트 타입(ARRIVED_MANUAL)로 구분한다.
 */
public enum ClientMode {
    NAVIGATION,// [활성 사용 맥락] 내비게이션/포그라운드 상호작용. 짧은 업로드 간격(예: 20~30s)·높은 정확도 기대.
    IDLE// [대기/저전력 맥락] 백그라운드/절전. 업로드 간격 길게(예: 45~60s), 정확도 임계 상향 조정 가능.
}
